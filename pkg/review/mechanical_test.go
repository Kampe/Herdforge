func TestMechanicalVerdict_StaleFor(t *testing.T) {
	v := EvaluateMechanical("sha1", "patch1", []FileChange{{Path: "README.md", Added: []string{"x"}}}, passChecks("preflight", "secret-scan", "link-check"), DefaultMechanicalPolicy())
	if v.StaleFor("sha1") {
		t.Error("verdict must not be stale for the SHA it was computed against")
	}
	if !v.StaleFor("sha2") {
		t.Error("verdict must be stale once HEAD moves to a new commit")
	}
}

func TestRequiredChecks_Deterministic(t *testing.T) {
	files := []FileChange{{Path: "README.md", Added: []string{"doc"}}}
	a := RequiredChecks(files, DefaultMechanicalPolicy())
	b := RequiredChecks(files, DefaultMechanicalPolicy())
	if len(a) != len(b) {
		t.Fatalf("non-deterministic required check set: %v vs %v", a, b)
	}
	for i := range a {
		if a[i] != b[i] {
			t.Fatalf("non-deterministic required check order: %v vs %v", a, b)
		}
	}
}
