func TestEvaluateMechanical_ApprovesCleanDocsChange(t *testing.T) {
	files := []FileChange{{Path: "README.md", Added: []string{"a doc line"}}}
	checks := passChecks("preflight", "secret-scan", "link-check")
	v := EvaluateMechanical("sha1", "patch1", files, checks, DefaultMechanicalPolicy())
	if !v.Approved || v.Tier != TierR0RiskMechanical {
		t.Fatalf("expected approved R0, got approved=%v tier=%s reasons=%v", v.Approved, v.Tier, v.Reasons)
	}
	if v.ClassifierVersion != MechanicalClassifierVersion {
		t.Errorf("expected classifier version bound, got %q", v.ClassifierVersion)
	}
	if v.VerificationDigest == "" {
		t.Error("expected non-empty verification digest")
	}
}

func TestEvaluateMechanical_MixedDiffEscalatesToHighestTier(t *testing.T) {
	files := []FileChange{
		{Path: "README.md", Added: []string{"doc"}},
		{Path: "pkg/auth/jwt.go", Added: []string{"func Sign() {}"}},
	}
	checks := passChecks("preflight", "secret-scan", "format-lint", "tests", "non-vacuity")
	v := EvaluateMechanical("sha1", "patch1", files, checks, DefaultMechanicalPolicy())
	if v.Approved {
		t.Fatal("mixed R0/R3 diff must not approve at R0")
	}
	if v.Tier != TierR3RiskCritical {
		t.Errorf("mixed diff must escalate to the highest tier observed, got %s", v.Tier)
	}
}

